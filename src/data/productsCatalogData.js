/**
 * Flat list of all products for search, details lookup, and dynamic routing
 */
export const allProductsList = productCategoriesHierarchy.flatMap((category) =>
  category.subcategories.flatMap((subcategory) =>
    subcategory.products.map((product) => ({
      ...product,
      categoryName: category.name,
      categorySlug: category.slug,
      subcategoryName: subcategory.name,
      subcategorySlug: subcategory.slug,
    }))
  )
);

export const getProductBySlug = (slug) => {
  return allProductsList.find((p) => p.slug === slug);
};

export const getCategoryBySlug = (categorySlug) => {
  return productCategoriesHierarchy.find((c) => c.slug === categorySlug);
};
