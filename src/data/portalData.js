const STORAGE_KEY_POS = 'txco_portal_pos';
const STORAGE_KEY_TCS = 'txco_portal_tcs';

export function getStoredPurchaseOrders() {
  if (typeof window === 'undefined') return mockPurchaseOrders;
  try {
    const raw = localStorage.getItem(STORAGE_KEY_POS);
    if (!raw) {
      localStorage.setItem(STORAGE_KEY_POS, JSON.stringify(mockPurchaseOrders));
      return mockPurchaseOrders;
    }
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : mockPurchaseOrders;
  } catch (e) {
    return mockPurchaseOrders;
  }
}

export function saveStoredPurchaseOrder(po) {
  if (typeof window === 'undefined') return po;
  try {
    const current = getStoredPurchaseOrders();
    const existingIndex = current.findIndex(
      (item) => String(item.poNumber).trim() === String(po.poNumber).trim()
    );
    let updated;
    if (existingIndex >= 0) {
      updated = [...current];
      updated[existingIndex] = { ...updated[existingIndex], ...po };
    } else {
      updated = [po, ...current];
    }
    localStorage.setItem(STORAGE_KEY_POS, JSON.stringify(updated));
    window.dispatchEvent(new Event('txco_portal_data_updated'));
    return updated;
  } catch (e) {
    console.error('Error saving PO:', e);
    return [];
  }
}

export function deleteStoredPurchaseOrder(poNumber) {
  if (typeof window === 'undefined') return [];
  try {
    const current = getStoredPurchaseOrders();
    const updated = current.filter(
      (item) => String(item.poNumber).trim() !== String(poNumber).trim()
    );
    localStorage.setItem(STORAGE_KEY_POS, JSON.stringify(updated));
    window.dispatchEvent(new Event('txco_portal_data_updated'));
    return updated;
  } catch (e) {
    console.error('Error deleting PO:', e);
    return [];
  }
}

